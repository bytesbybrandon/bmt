const fs = require("node:fs");
const path = require("node:path");

const projectDir = path.resolve(__dirname, "..");
const contentlayerIndexPath = path.join(
  projectDir,
  ".contentlayer",
  "generated",
  "BlogPost",
  "_index.json",
);
const generatedDir = path.resolve(
  projectDir,
  "src",
  "contentlayer-generated",
);
const generatedPostsDir = path.join(generatedDir, "BlogPost");
const generatedIndexPath = path.join(generatedPostsDir, "_index.json");
const generatedModulePath = path.join(generatedDir, "index.js");

if (!fs.existsSync(contentlayerIndexPath)) {
  throw new Error(`Contentlayer output is missing: ${contentlayerIndexPath}`);
}

const contentlayerPosts = JSON.parse(
  fs.readFileSync(contentlayerIndexPath, "utf8"),
);

if (!Array.isArray(contentlayerPosts)) {
  throw new Error("Contentlayer blog index must be an array.");
}

const posts = contentlayerPosts.map((post) => ({
  ...post,
  body: {
    raw: post.body?.raw || "",
    code: "",
  },
}));

fs.mkdirSync(generatedPostsDir, { recursive: true });

for (const entry of fs.readdirSync(generatedPostsDir, {
  withFileTypes: true,
})) {
  if (!entry.isFile() || !entry.name.endsWith(".json")) {
    continue;
  }

  const generatedFilePath = path.resolve(generatedPostsDir, entry.name);
  if (path.dirname(generatedFilePath) !== generatedPostsDir) {
    throw new Error(`Unexpected generated file path: ${generatedFilePath}`);
  }

  fs.unlinkSync(generatedFilePath);
}

fs.writeFileSync(generatedIndexPath, `${JSON.stringify(posts, null, 2)}\n`);
fs.writeFileSync(
  generatedModulePath,
  [
    "// This file is auto-generated by scripts/sync-contentlayer-cra.js.",
    'import allBlogPosts from "./BlogPost/_index.json";',
    "",
    "export { allBlogPosts };",
    "export const allDocuments = [...allBlogPosts];",
    "",
  ].join("\n"),
);
